// Двери: rot 0 — на горизонтальной стене, створка в +y (на юг); 180 — в −y; 270 — на вертикальной стене, створка в +x; 90 — в −x.
const fs = require("fs"), path = require("path");
const r3 = v => Math.round(v * 1000) / 1000;
const KB = require("../src/office-kb.js");
const C = { hall: "#EDE8DE", maket: "#F2F0EA", wait: "#F3E6CF", kids: "#F4D36B", off: "#DAE8F6", meet: "#F7D9C2", wc: "#CFE8E6",
  svc: "#E2E2DC", staff: "#E0ECD8", back: "#E5DBF2", circ: "#EDEDE6", out: "#F6F6F3", deal: "#E8DCC8" };

function project(pfx, AX, AY) {
  let n = 0; const uid = () => pfx + (++n).toString(36);
  const items = [];
  // помещение по чертёжным координатам x0..x1, y0..y1
  const room = (name, x0, x1, y0, y1, cat, border, o = {}) => { const it = Object.assign({ id: uid(), t: "room", lv: 0, name,
    x: r3(x0 + AX), y: r3(y0 + AY), w: r3(x1 - x0), h: r3(y1 - y0), cat, border, sub: false, ph: 3.0, color: (KB.CAT[cat] || KB.CAT.circ).c }, o); items.push(it); return it; };
  const item = (k, x, y, w, h, rot = 0, o = {}) => { const it = Object.assign({ id: uid(), t: "item", lv: 0, k, x: r3(x + AX), y: r3(y + AY), w: r3(w), h: r3(h), rot, flip: false, label: "" }, o); items.push(it); return it; };
  // дверь в горизонтальной стене (ось стены Y, проём x0..x1), dir +1 — створка на юг (+y), −1 — на север
  const dH = (x0, x1, Y, dir, { k = "door9", ...o } = {}) => { const w = x1 - x0, h = k === "door18" ? w / 2 + 0.3 : w + 0.3;
    return item(k, x0, dir > 0 ? Y - 0.15 : Y + 0.15 - h, w, h, dir > 0 ? 0 : 180, o); };
  // дверь в вертикальной стене (ось стены X, проём y0..y1), dir +1 — створка на восток (+x), −1 — на запад
  const dV = (y0, y1, X, dir, { k = "door9", ...o } = {}) => { const w = y1 - y0, h = k === "door18" ? w / 2 + 0.3 : w + 0.3;
    return item(k, dir > 0 ? X - 0.15 : X + 0.15 - h, y0, w, h, dir > 0 ? 270 : 90, o); };
  // отдельная стена / перегородка по оси (x1,y1)–(x2,y2)
  const wall = (x1, y1, x2, y2, kind = "part", th = 0.15) => { const it = { id: uid(), t: "wall", lv: 0, kind, x1: r3(x1 + AX), y1: r3(y1 + AY), x2: r3(x2 + AX), y2: r3(y2 + AY), th }; items.push(it); return it; };
  return { items, room, item, dH, dV, wall };
}

